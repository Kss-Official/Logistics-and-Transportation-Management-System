function getCategoryIcon(category: string) {
  const c = category.toLowerCase();
  if (c.includes('order')) return <Package size={13} color="#2563eb" />;
  if (c.includes('ship')) return <Truck size={13} color="#0284c7" />;
  if (c.includes('track')) return <Navigation size={13} color="#059669" />;
  if (c.includes('bill') || c.includes('invoice')) return <Receipt size={13} color="#d97706" />;
  if (c.includes('fleet') || c.includes('vehicle')) return <Truck size={13} color="#7c3aed" />;
  if (c.includes('portal')) return <Layers size={13} color="#4f46e5" />;
  return <ShieldCheck size={13} color="#2563eb" />;
}

